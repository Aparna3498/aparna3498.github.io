function setLanguage(lang) {
  const dict = translations[lang] || translations.en;
  document.documentElement.lang = lang;
  document.documentElement.dataset.currentLang = lang;
  localStorage.setItem('portfolioLang', lang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key]) el.textContent = dict[key];
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
    btn.setAttribute('aria-pressed', btn.dataset.lang === lang ? 'true' : 'false');
  });

  document.title = lang === 'de'
    ? 'Aparna Dharmalingam | Funktionale Sicherheit'
    : 'Aparna Dharmalingam | Functional Safety Engineer';

  const desc = document.querySelector('meta[name="description"]');
  if (desc) {
    desc.setAttribute('content', lang === 'de'
      ? 'Aparna Dharmalingam — Portfolio für Funktionale Sicherheit, ISO 26262, ADAS und Systemsicherheit.'
      : 'Aparna Dharmalingam — Functional Safety, ISO 26262, ADAS & System Safety portfolio.');
  }
}

document.querySelectorAll('.lang-btn').forEach(btn => {
  btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
});

const preferred = localStorage.getItem('portfolioLang') || 'en';
setLanguage(preferred);

const btn = document.querySelector('.menu-btn');
const nav = document.querySelector('.nav-links');
if (btn && nav) {
  btn.addEventListener('click', () => {
    const open = nav.classList.toggle('open');
    btn.setAttribute('aria-expanded', open ? 'true' : 'false');
  });
  nav.querySelectorAll('a').forEach(a => a.addEventListener('click', () => {
    nav.classList.remove('open');
    btn.setAttribute('aria-expanded', 'false');
  }));
}
